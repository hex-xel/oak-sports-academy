import sharp from "sharp";
import type { ImageInput } from "../../src/modules/documents/image-validation.js";

/** Synthetic acceptance/rejection input; contains no participant document or personal data. */
export type ImageDemoCase = Readonly<{ name: string; input: ImageInput; accepted: boolean }>;

/**
 * Build deterministic synthetic images for the owner-run algorithm demo and focused checks.
 * @returns Real encoded JPEG/PNG inputs and deliberately invalid variants, all in memory.
 * @throws Native fixture-encoding failures; no files, network or database are accessed.
 * @remarks The generated byte noise is test imagery, not cryptographic randomness.
 */
export async function imageValidationFixtures(): Promise<ImageDemoCase[]> {
  const pixels = Buffer.alloc(400 * 400 * 3);
  let state = 17;
  for (let index = 0; index < pixels.length; index++) {
    state = (Math.imul(state, 1664525) + 1013904223) >>> 0;
    pixels[index] = state >>> 24;
  }
  const encode = () => sharp(pixels, { raw: { width: 400, height: 400, channels: 3 } });
  const png = await encode().png().toBuffer();
  const jpeg = await encode().jpeg({ quality: 85 }).toBuffer();
  const small = await encode().resize(399, 400, { fit: "fill" }).png().toBuffer();
  const disguised = Buffer.alloc(5120, 0x20);
  disguised.write("MZ synthetic executable header; this is not an image");
  const fakeHeader = Buffer.alloc(5120);
  png.copy(fakeHeader, 0, 0, 8);
  const input = (bytes: Buffer, fileName = "synthetic.png", mimeType = "image/png"): ImageInput =>
    ({ bytes, fileName, mimeType });
  return [
    { name: "Valid PNG", input: input(png), accepted: true },
    { name: "Valid JPEG", input: input(jpeg, "synthetic.jpg", "image/jpeg"), accepted: true },
    { name: "Executable renamed .png", input: input(disguised), accepted: false },
    { name: "PNG declared JPEG", input: input(png, "synthetic.jpg", "image/jpeg"), accepted: false },
    { name: "PNG with .jpg extension", input: input(png, "synthetic.jpg"), accepted: false },
    { name: "Forged PNG signature only", input: input(fakeHeader), accepted: false },
    { name: "Truncated PNG pixels", input: input(png.subarray(0, Math.floor(png.length / 2))), accepted: false },
    { name: "Below 400px minimum", input: input(small), accepted: false },
    { name: "Below 5 KiB", input: input(png.subarray(0, 5119)), accepted: false },
    { name: "Above 5 MiB", input: input(Buffer.alloc(5 * 1024 * 1024 + 1)), accepted: false },
    { name: "False declared byte count", input: { ...input(png), declaredByteSize: png.length - 1 }, accepted: false },
    { name: "SVG renamed .png", input: input(Buffer.from(`<svg>${" ".repeat(5120)}</svg>`)), accepted: false },
  ];
}
